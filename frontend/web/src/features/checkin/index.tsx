import clsx from 'clsx'
import { Annoyed, ArrowRight, Check, ClipboardCheck, ClipboardPen, Frown, Laugh, Meh, Smile, type LucideIcon } from 'lucide-react'
import { useState } from 'react'
import { useAppStore } from '../../state/store'
import type { CheckIn } from '../../types/domain'
import { Badge, Button, IconButton } from '../../components/ui'
import { formatUtcTime, relTime } from '../../components/format'
import { Modal } from '../mission/Modal'

export interface CheckInButtonProps {
  astronautId: string
  /** compact = icon button for crew cards and top bar, prominent = large call to action in Crew view. */
  variant?: 'compact' | 'prominent'
}

type ScaleKey = 'mood' | 'fatigue' | 'stress' | 'sleepQuality'

const SCALES: { key: ScaleKey; question: string; words: [string, string, string, string, string]; highIsGood: boolean }[] = [
  { key: 'mood', question: 'How is your mood?', words: ['Very low', 'Low', 'Okay', 'Good', 'Very good'], highIsGood: true },
  { key: 'fatigue', question: 'How tired do you feel?', words: ['Rested', 'Slightly tired', 'Tired', 'Very tired', 'Exhausted'], highIsGood: false },
  { key: 'stress', question: 'How stressed do you feel?', words: ['Calm', 'A little', 'Moderate', 'High', 'Very high'], highIsGood: false },
  { key: 'sleepQuality', question: 'How well did you sleep?', words: ['Very poorly', 'Poorly', 'Fair', 'Well', 'Very well'], highIsGood: true },
]

/** Face by "how good" (0 = worst, 4 = best), so the face always reads the same way. */
const FACES: LucideIcon[] = [Frown, Annoyed, Meh, Smile, Laugh]

const SYMPTOMS = ['headache', 'congestion', 'back pain', 'nausea', 'eye discomfort', 'trouble sleeping'] as const
const NONE = 'none'

const DAY = 86400000

function word(key: ScaleKey, v: number): string {
  return SCALES.find((s) => s.key === key)!.words[Math.min(5, Math.max(1, Math.round(v))) - 1]!.toLowerCase()
}

function useLastCheckIn(astronautId: string): CheckIn | undefined {
  return useAppStore((s) => {
    let best: CheckIn | undefined
    for (const c of s.checkIns) if (c.astronautId === astronautId && (!best || c.at > best.at)) best = c
    return best
  })
}

function useDoneToday(astronautId: string): boolean {
  return useAppStore((s) => {
    const today = Math.floor(s.clock.simNow / DAY)
    return s.checkIns.some((c) => c.astronautId === astronautId && Math.floor(c.at / DAY) === today)
  })
}

function OriginBadge({ c }: { c: CheckIn }) {
  return c.data_origin === 'MANUAL' ? (
    <Badge tone="accent" title="Answers typed in this app">
      Typed by crew
    </Badge>
  ) : (
    <Badge tone="sim" title="Auto-generated by the simulator">
      Simulated
    </Badge>
  )
}

function LastSummary({ c, now }: { c: CheckIn; now: number }) {
  const symptoms = c.symptoms.filter((s) => s !== NONE)
  return (
    <div className="rounded-xl bg-white/[0.03] p-3 ring-1 ring-white/[0.06]">
      <div className="flex items-center justify-between gap-2">
        <span className="text-[11px] font-semibold tracking-[0.14em] text-ink-500 uppercase">Last check-in</span>
        <span className="flex items-center gap-1.5">
          <span className="tabular text-[11px] text-ink-500" title={`${formatUtcTime(c.at)} UTC (sim)`}>
            {relTime(c.at, now)} · {formatUtcTime(c.at, false)} UTC
          </span>
          <OriginBadge c={c} />
        </span>
      </div>
      <dl className="mt-2 grid grid-cols-2 gap-x-4 gap-y-1 text-xs sm:grid-cols-4">
        {SCALES.map((s) => (
          <div key={s.key}>
            <dt className="text-[10px] text-ink-500">{s.key === 'sleepQuality' ? 'Sleep' : s.key === 'mood' ? 'Mood' : s.key === 'fatigue' ? 'Fatigue' : 'Stress'}</dt>
            <dd className="font-semibold text-ink-100 first-letter:uppercase">
              {word(s.key, c[s.key])} <span className="tabular font-normal text-ink-500">{c[s.key]}/5</span>
            </dd>
          </div>
        ))}
      </dl>
      <div className="mt-1.5 text-xs text-ink-300">
        <span className="text-ink-500">Symptoms:</span> {symptoms.length ? symptoms.join(', ') : 'none reported'}
        {c.note && <span className="mt-0.5 block text-ink-500 italic">"{c.note}"</span>}
      </div>
    </div>
  )
}

function Scale({ def, value, onChange }: { def: (typeof SCALES)[number]; value: number | null; onChange: (v: number) => void }) {
  const name = `checkin-${def.key}`
  return (
    <fieldset>
      <legend className="text-[13px] font-semibold text-ink-100">{def.question}</legend>
      <div className="mt-2 grid grid-cols-5 gap-1.5">
        {def.words.map((w, i) => {
          const v = i + 1
          const good = def.highIsGood ? i : 4 - i
          const Face = FACES[good]!
          const on = value === v
          return (
            <label
              key={w}
              className={clsx(
                'flex min-h-[68px] cursor-pointer flex-col items-center justify-center gap-1 rounded-xl px-1 py-2 text-center transition-colors select-none',
                'has-[:focus-visible]:outline-2 has-[:focus-visible]:outline-offset-2 has-[:focus-visible]:outline-accent',
                on ? 'bg-accent/15 text-accent ring-1 ring-accent/50' : 'bg-white/[0.03] text-ink-300 ring-1 ring-white/[0.06] hover:bg-white/[0.07] hover:text-ink-100',
              )}
            >
              <input type="radio" name={name} value={v} checked={on} onChange={() => onChange(v)} className="sr-only" />
              <Face size={22} strokeWidth={on ? 2.2 : 1.8} aria-hidden />
              <span className="text-[11px] leading-tight font-medium">{w}</span>
            </label>
          )
        })}
      </div>
    </fieldset>
  )
}

function CheckInForm({ astronautId, onDone }: { astronautId: string; onDone: (at: number) => void }) {
  const [values, setValues] = useState<Record<ScaleKey, number | null>>({ mood: null, fatigue: null, stress: null, sleepQuality: null })
  const [symptoms, setSymptoms] = useState<string[]>([])
  const [note, setNote] = useState('')
  const complete = SCALES.every((s) => values[s.key] != null)
  const missing = SCALES.filter((s) => values[s.key] == null).length

  const toggle = (sym: string) => {
    setSymptoms((cur) => {
      if (sym === NONE) return cur.includes(NONE) ? [] : [NONE]
      const base = cur.filter((x) => x !== NONE)
      return base.includes(sym) ? base.filter((x) => x !== sym) : [...base, sym]
    })
  }

  const submit = () => {
    if (!complete) return
    const s = useAppStore.getState()
    s.submitCheckIn({
      astronautId,
      mood: values.mood!,
      fatigue: values.fatigue!,
      stress: values.stress!,
      sleepQuality: values.sleepQuality!,
      symptoms: symptoms.length ? symptoms : [NONE],
      note: note.trim(),
    })
    onDone(s.clock.simNow)
  }

  return (
    <form
      onSubmit={(e) => {
        e.preventDefault()
        submit()
      }}
      className="flex flex-col gap-5"
    >
      {SCALES.map((def) => (
        <Scale key={def.key} def={def} value={values[def.key]} onChange={(v) => setValues((cur) => ({ ...cur, [def.key]: v }))} />
      ))}
      <fieldset>
        <legend className="text-[13px] font-semibold text-ink-100">Anything bothering you?</legend>
        <div className="mt-2 flex flex-wrap gap-1.5">
          {[...SYMPTOMS, NONE].map((sym) => {
            const on = symptoms.includes(sym)
            return (
              <button
                key={sym}
                type="button"
                aria-pressed={on}
                onClick={() => toggle(sym)}
                className={clsx(
                  'focus-ring inline-flex min-h-[36px] items-center gap-1 rounded-full px-3.5 text-xs font-medium transition-colors first-letter:uppercase',
                  on ? 'bg-accent/15 text-accent ring-1 ring-accent/50' : 'bg-white/[0.03] text-ink-300 ring-1 ring-white/[0.08] hover:bg-white/[0.07] hover:text-ink-100',
                )}
              >
                {on && <Check size={12} strokeWidth={3} aria-hidden />}
                {sym === NONE ? 'None' : sym.charAt(0).toUpperCase() + sym.slice(1)}
              </button>
            )
          })}
        </div>
      </fieldset>
      <label className="block">
        <span className="text-[13px] font-semibold text-ink-100">
          Note <span className="font-normal text-ink-500">(optional)</span>
        </span>
        <textarea
          value={note}
          onChange={(e) => setNote(e.target.value.slice(0, 280))}
          rows={2}
          placeholder="Anything the crew medical officer should know"
          className="focus-ring mt-2 block w-full resize-none rounded-xl bg-white/[0.03] px-3 py-2 text-[13px] text-ink-100 ring-1 ring-white/[0.08] placeholder:text-ink-500 focus:outline-none"
        />
      </label>
      <div className="flex items-center justify-between gap-3">
        <span className="text-[11px] text-ink-500">{complete ? 'Ready to save.' : `${missing} question${missing === 1 ? '' : 's'} left`}</span>
        <Button type="submit" variant="primary" disabled={!complete} className="px-4 py-2 text-[13px]">
          <Check size={14} strokeWidth={3} aria-hidden /> Submit check-in
        </Button>
      </div>
    </form>
  )
}

function CheckInModal({ astronautId, onClose }: { astronautId: string; onClose: () => void }) {
  const callsign = useAppStore((s) => s.crew.find((c) => c.id === astronautId)?.callsign ?? astronautId)
  const last = useLastCheckIn(astronautId)
  const now = useAppStore((s) => Math.floor(s.clock.simNow / 60000) * 60000)
  const [savedAt, setSavedAt] = useState<number | null>(null)
  return (
    <Modal
      open
      onClose={onClose}
      size="md"
      title={`Daily check-in · ${callsign}`}
      subtitle="About 30 seconds. Self report, saved as a manual entry. Not a diagnosis."
      icon={<ClipboardPen size={17} className="text-accent" aria-hidden />}
    >
      {savedAt != null ? (
        <div className="flex flex-col items-center gap-3 py-6 text-center">
          <span className="flex h-12 w-12 items-center justify-center rounded-full bg-accent/15 text-accent ring-1 ring-accent/40">
            <Check size={24} strokeWidth={3} aria-hidden />
          </span>
          <div className="text-base font-semibold text-ink-100">Thanks, {callsign}. Check-in saved.</div>
          <p className="max-w-sm text-xs leading-relaxed text-ink-300">
            Saved at {formatUtcTime(savedAt, false)} UTC (sim). Your answers help separate how you feel from what the sensors see. They never replace a conversation with the crew medical officer.
          </p>
          <Button variant="ghost" onClick={onClose} className="mt-1">
            Close
          </Button>
        </div>
      ) : (
        <div className="flex flex-col gap-5">
          {last && <LastSummary c={last} now={now} />}
          <CheckInForm astronautId={astronautId} onDone={setSavedAt} />
        </div>
      )}
    </Modal>
  )
}

/** Daily subjective check-in trigger. Opens a short questionnaire modal. */
export function CheckInButton({ astronautId, variant = 'compact' }: CheckInButtonProps) {
  const [open, setOpen] = useState(false)
  const callsign = useAppStore((s) => s.crew.find((c) => c.id === astronautId)?.callsign)
  const doneToday = useDoneToday(astronautId)
  const last = useLastCheckIn(astronautId)
  const now = useAppStore((s) => Math.floor(s.clock.simNow / 60000) * 60000)
  if (!callsign) return null
  const modal = open && <CheckInModal astronautId={astronautId} onClose={() => setOpen(false)} />

  if (variant === 'prominent') {
    return (
      <div data-tour="checkin" className="relative overflow-hidden rounded-2xl bg-gradient-to-br from-accent/[0.09] to-white/[0.02] p-4 ring-1 ring-accent/20">
        <div className="flex items-start gap-3">
          <span className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-accent/15 text-accent">
            {doneToday ? <ClipboardCheck size={20} aria-hidden /> : <Smile size={20} aria-hidden />}
          </span>
          <div className="min-w-0 flex-1">
            {doneToday && last ? (
              <>
                <div className="text-[15px] font-semibold text-ink-100">Checked in today</div>
                <div className="mt-0.5 text-xs leading-relaxed text-ink-300">
                  {formatUtcTime(last.at, false)} UTC · mood {word('mood', last.mood)}, fatigue {word('fatigue', last.fatigue).toLowerCase()}, sleep {word('sleepQuality', last.sleepQuality)}
                </div>
                <div className="mt-1.5">
                  <OriginBadge c={last} />
                </div>
              </>
            ) : (
              <>
                <div className="text-[15px] font-semibold text-ink-100">How do you feel today, {callsign}?</div>
                <div className="mt-0.5 text-xs text-ink-300">Daily check-in · 30 seconds · mood, fatigue, stress and sleep</div>
                {last && <div className="mt-1 text-[11px] text-ink-500">Last one {relTime(last.at, now)}</div>}
              </>
            )}
          </div>
        </div>
        <Button variant={doneToday ? 'ghost' : 'primary'} onClick={() => setOpen(true)} className="mt-3 w-full py-2 text-[13px]">
          {doneToday ? 'Update check-in' : 'Start check-in'} <ArrowRight size={14} aria-hidden />
        </Button>
        {modal}
      </div>
    )
  }

  return (
    <>
      <IconButton
        data-tour="checkin"
        label={doneToday ? `Daily check-in for ${callsign}: done today` : `Daily check-in for ${callsign}: not done today`}
        onClick={() => setOpen(true)}
        size="sm"
      >
        {doneToday ? <ClipboardCheck size={15} aria-hidden /> : <ClipboardPen size={15} aria-hidden />}
        {!doneToday && <span className="absolute -top-0.5 -right-0.5 h-2 w-2 rounded-full bg-accent ring-2 ring-space-900" aria-hidden />}
      </IconButton>
      {modal}
    </>
  )
}
